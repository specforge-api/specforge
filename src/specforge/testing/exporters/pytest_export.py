"""Pytest code generator for SpecForge test plans."""

import json
from typing import List

from specforge.testing.invariants import TestCase


class PytestExporter:
    """Compiles SpecForge TestCases into ready-to-run pytest code."""

    @classmethod
    def export(
        cls,
        test_cases: List[TestCase],
        base_url: str = "http://localhost:8000",
        module_name: str = "test_api_contracts.py",
    ) -> str:
        """Generate clean, formatted pytest code."""
        cases_repr: List[str] = []

        for tc in test_cases:
            payload_json = json.dumps(tc.payload) if tc.payload is not None else "None"
            query_json = json.dumps(tc.query_params) if tc.query_params else "None"
            desc_escaped = tc.description.replace('"', '\\"')

            case_str = (
                f'    (\n'
                f'        "{tc.endpoint}",\n'
                f'        "{tc.method.upper()}",\n'
                f'        {payload_json},\n'
                f'        {query_json},\n'
                f'        {tc.expected_status},\n'
                f'        {tc.is_negative_test},\n'
                f'        "{desc_escaped}",\n'
                f'    ),'
            )
            cases_repr.append(case_str)

        cases_block = "\n".join(cases_repr)

        code = f'''# Auto-generated by SpecForge
# Contract Boundary & Invariant Test Suite
import pytest
import httpx

BASE_URL = "{base_url}"

@pytest.mark.parametrize(
    "endpoint,method,payload,query_params,expected_status,is_negative,description",
    [
{cases_block}
    ]
)
def test_specforge_contract_boundaries(
    endpoint: str,
    method: str,
    payload,
    query_params,
    expected_status: int,
    is_negative: bool,
    description: str,
):
    """Execute boundary test and assert Zero-500s invariant and contract validation."""
    with httpx.Client(base_url=BASE_URL, timeout=10.0) as client:
        kwargs = {{}}
        if payload is not None:
            kwargs["json"] = payload
        if query_params is not None:
            kwargs["params"] = query_params

        response = client.request(method, endpoint, **kwargs)

        # Invariant 1: Server must NEVER crash with HTTP 500 on client inputs
        assert response.status_code != 500, (
            f"CRITICAL 500 SERVER CRASH: '{{description}}' triggered an unhandled exception!"
        )

        # Invariant 2: Negative tests must be cleanly rejected with 400 or 422
        if is_negative:
            assert response.status_code in (400, 422), (
                f"SCHEMA LEAK on '{{description}}': expected 400/422 rejection, "
                f"got HTTP {{response.status_code}}. Response: {{response.text}}"
            )
        else:
            assert 200 <= response.status_code < 300, (
                f"Happy path failed on '{{description}}': got HTTP {{response.status_code}}."
            )
'''
        return code
